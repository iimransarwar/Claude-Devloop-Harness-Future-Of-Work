#!/usr/bin/env bash
# Prints tests/ansi-c-table.ts (the eleventh round, V2): what real bash makes of
# the body of a `$'…'` word, for every one-character escape body (`\X` and
# `\cX`, X each printable ASCII character), a few where a NUL ends the
# string, and the forms of `\x{H…}` (the thirteenth round, BB3).
# tests/shell.test.ts compares hooks/shell.ts's decoder with it;
# tests/smoke.sh runs this again and checks the committed table is what this
# bash says. Usage: bash tests/ansi-c-table.sh > tests/ansi-c-table.ts
set -eu

quote() { # a body as a TypeScript string literal, in double quotes
  local s=${1//\\/\\\\}
  printf '"%s"' "${s//\"/\\\"}"
}
bytes() { # what bash's $'…' makes of a body, in hex
  eval "printf %s \$'$1'" | od -An -tx1 | tr -d ' \n'
}

bodies=()
for code in $(seq 32 126); do
  c=$(printf "\\$(printf '%03o' "$code")")
  bodies+=("\\$c")
  # `\c'` cannot be written inside $'…' (the quote ends it) and `\c\` escapes the quote; `\c\\` is bash's spelling.
  if [ "$c" != "'" ] && [ "$c" != "\\" ]; then
    bodies+=("\\c$c")
  fi
done
bodies+=('\c\\' 'a\c\\b' 'a\0b' 'a\x00b' 'a\u0000b' 'a\c@b' 'a\c b' 'a\c`b' 'a\cxb' 'ma\c`in')
# `\x{H…}` (the thirteenth round, BB3): empty braces, a part that is not hex, a missing `}`, long values, past one byte.
bodies+=('a\x{65}b' 'tok\x{65}n' 'a\x{}b' 'a\x{g}b' 'a\x{65' 'a\x{65g}b' 'a\x{ 65}b' 'a\x{65}}b' 'a\x{{65}b' 'a\x{0065}b' 'a\x{6}b' 'a\x{7f}b'
  'a\x{100}b' 'a\x{1F600}b' 'a\x{000000000000000000065}b' 'a\x{fffffffffffffffffff41}b' 'a\x{1000000041}b' 'a\x{41}{42}b' 'a\x{-1}b' 'a\x{4a}\x{4B}b')

echo '// Generated by tests/ansi-c-table.sh from real bash; do not edit by hand (the eleventh round, V2).'
echo '// Each entry: the body of a `$'"'"'…'"'"'` word, and the bytes bash makes of it, in hex.'
echo 'export const BASH_ANSI_C: readonly (readonly [string, string])[] = ['
for body in "${bodies[@]}"; do
  printf '  [%s, "%s"],\n' "$(quote "$body")" "$(bytes "$body")"
done
echo ']'
